public class SimpleJavaProgram {
    public static void main(String[] args) {
        
        // Print "Hello, World!"
        System.out.println("Hello, World!");

        // Declare and initialize different data types
        int number = 10;           // Integer type
        double pi = 3.14159;        // Double (floating-point)
        char grade = 'A';           // Character type
        boolean isJavaFun = true;   // Boolean type

        // Perform some basic operations
        int sum = number + 5;       // Adding to the number
        double area = pi * 2 * 2;   // Calculate area of a circle with radius 2

        // Print the values of variables
        System.out.println("Number: " + number);
        System.out.println("Sum: " + sum);
        System.out.println("Pi value: " + pi);
        System.out.println("Area of circle: " + area);
        System.out.println("Grade: " + grade);
        System.out.println("Is Java fun? " + isJavaFun);
    }
}


// Output
/*Hello, World!
Number: 10
Sum: 15
Pi value: 3.14159
Area of circle: 12.56636
Grade: A
Is Java fun? true*/
